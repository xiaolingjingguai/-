MIN_H = 15        # 第6.1.1条


def stack_height(rows, h, open_top=False):
    """按第6.1.2条四舍五入取表列高度。返回 (表列高度, 限值, 说明) ；无法取值时限值为 None"""
    hs = [x[0] for x in rows]
    if h < MIN_H:
        return None, None, f"排气筒 {h:g} m 低于 15 m（第6.1.1条：排气筒最低高度不得低于 15 m；第3.3条：低于 15 m 的视为无组织排放源）"
    if h >= hs[-1]:
        if h == hs[-1] or open_top:
            return hs[-1], rows[-1][1], f"排气筒 {h:g} m，取表列 {'≥' if open_top else ''}{hs[-1]} m 标准值"
        return None, None, f"排气筒 {h:g} m 高于表2所列最高高度 {hs[-1]} m，标准未规定，信息不足"
    for (h1, q1), (h2, q2) in zip(rows, rows[1:]):
        if h1 <= h <= h2:
            if h == h1:
                return h1, q1, f"排气筒 {h:g} m，取表列 {h1} m 标准值"
            pick = (h2, q2) if (h - h1) >= (h2 - h1) / 2 else (h1, q1)
            return pick[0], pick[1], f"排气筒 {h:g} m 介于表列 {h1} m、{h2} m 之间，按第6.1.2条四舍五入取 {pick[0]} m"
    return None, None, "排气筒高度无法识别"
