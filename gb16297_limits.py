def rate_limit(rates, h, grade):
    """按附录 B 计算某高度的最高允许排放速率，返回 (速率, 计算说明)"""
    hs = sorted(rates)
    k = 0 if grade == 2 else 1
    if h in rates:
        return rates[h][k], f"表列 {h:g} m"
    if h > hs[-1]:
        hb = hs[-1]
        q = rates[hb][k] * (h / hb) ** 2
        return q, f"高于表列最高高度，外推 Q=Qb(h/hb)²，Qb={rates[hb][k]:g}，hb={hb} m（附录B式B2）"
    if h < hs[0]:
        hc = hs[0]
        q = rates[hc][k] * (h / hc) ** 2
        return q, f"低于表列最低高度，外推 Q=Qc(h/hc)²，Qc={rates[hc][k]:g}，hc={hc} m（附录B式B3）"
    lo = max(x for x in hs if x < h)
    hi = min(x for x in hs if x > h)
    qa, qb = rates[lo][k], rates[hi][k]
    q = qa + (qb - qa) * (h - lo) / (hi - lo)
    return q, f"内插 Q=Qa+(Qa+1-Qa)(h-ha)/(ha+1-ha)，{lo}~{hi} m 之间（附录B式B1）"
