from docx import Document


def table(doc, rows, note, merge_col0=False):
    t = doc.add_table(rows=len(rows) + 1, cols=len(rows[0]))
    t.style = "Table Grid"
    for i, r in enumerate(rows):
        for j, v in enumerate(r):
            t.cell(i, j).text = str(v)
    if merge_col0:                       # 第一列同名相邻单元格合并（模拟报告中的合并单元格）
        start = 1
        for i in range(2, len(rows) + 1):
            if i == len(rows) or rows[i][0] != rows[start][0]:
                if i - 1 > start:
                    txt = rows[start][0]
                    m = t.cell(start, 0).merge(t.cell(i - 1, 0))
                    m.text = txt
                start = i
    last = t.rows[len(rows)].cells
    m = last[0].merge(last[-1])
    m.text = note


